'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = __dirname;
const context = { window: {}, console: { warn: (message) => { throw new Error(message); }, log: () => {} } };
vm.runInNewContext(fs.readFileSync(path.join(root, 'question-bank.js'), 'utf8'), context, { filename: 'question-bank.js' });
const questions = context.window.INTERVIEW_QUESTIONS;
assert.equal(context.window.INTERVIEW_QUESTION_BANK_VERSION, '3.1.0');
assert.ok(Array.isArray(questions));
assert.equal(questions.length, 500, `expected 500 valid questions, got ${questions.length}`);
const allowedDifficulty = new Set(['Beginner','Intermediate','Interview']);
const allowedType = new Set(['Concept','Practical','Scenario','Communication','Behavioral','Technical']);
const ids = new Set(), texts = new Set(), categories = new Set(), roles = new Set();
for (const q of questions) {
 for (const field of ['id','category','difficulty','type','question','answer','tip']) assert.equal(typeof q[field], 'string', `${q.id || 'unknown'}: ${field} must be string`);
 for (const field of ['id','category','question','answer']) assert.ok(q[field].trim(), `${q.id}: ${field} cannot be blank`);
 assert.ok(allowedDifficulty.has(q.difficulty), `${q.id}: invalid difficulty`); assert.ok(allowedType.has(q.type), `${q.id}: invalid type`);
 assert.ok(!ids.has(q.id), `duplicate ID: ${q.id}`); ids.add(q.id);
 const normalized=q.question.trim().toLocaleLowerCase('en'); assert.ok(!texts.has(normalized), `duplicate question text: ${q.question}`); texts.add(normalized);
 assert.ok(Array.isArray(q.roles)&&q.roles.length>0, `${q.id}: role tags missing`); q.roles.forEach(r=>roles.add(r)); categories.add(q.category);
 if(q.source) assert.ok(/^https:\/\//.test(q.source.url), `${q.id}: source must be HTTPS`);
}
assert.equal(categories.size,13);
assert.ok(['Data Analyst','BI Analyst','Junior BI Developer','Junior Data Engineer','MIS/Reporting Analyst','Business Analyst','All roles'].every(r=>roles.has(r)));
for(let i=1;i<=100;i++) assert.equal(questions[i-1].id,`iq-${String(i).padStart(3,'0')}`,'legacy question IDs changed');
assert.equal(questions[300].id,'iq-301');
assert.ok(questions.some(q=>q.followUp));
vm.runInNewContext(fs.readFileSync(path.join(root, 'sql-lab.js'), 'utf8'), context, { filename: 'sql-lab.js' });
const lab=context.window.INTERVIEW_SQL_LAB;assert.equal(lab.tables.length,4);assert.equal(lab.exercises.length,20);assert.equal(new Set(lab.exercises.map(e=>e.id)).size,20);
for(const table of lab.tables){assert.ok(table.columns.length);for(const row of table.rows)assert.equal(row.length,table.columns.length,`${table.name}: row/schema mismatch`)}
for(const ex of lab.exercises) for(const f of ['id','level','topic','title','task','hint','solution','explanation','expected']) assert.ok(typeof ex[f]==='string'&&ex[f].trim(),`${ex.id}: missing ${f}`);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');for(const id of ['question-role','question-category','question-difficulty','question-type','question-load-error','question-bank-list'])assert.ok(html.includes(`id="${id}"`),`missing ${id}`);
assert.ok(html.indexOf('src="question-bank.js"')<html.indexOf('src="app.js"'));
assert.ok(html.includes('id="bank-total">500</strong>'));
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');assert.ok(sw.includes("const CACHE_NAME = 'interview-quest-v3-1'"));for(const f of ['./index.html','./style.css','./app.js','./question-bank.js','./sql-lab.js','./manifest.webmanifest','./icon.svg'])assert.ok(sw.includes(f),`service worker misses ${f}`);
JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
console.log(`PASS: ${questions.length} unique question records, ${categories.size} categories, ${roles.size} role labels; 20 SQL exercises across ${lab.tables.length} sample tables.`);
console.log('PASS: required question fields, levels/types, references, legacy IDs, sample-table schemas, roadmap count label, script/cache setup.');
